def analyze_answer(answer_text: str) -> dict:
    """Анализирует ответ ученика и возвращает баллы по типам Климова"""
    
    # Промпт для YandexGPT
    prompt = f"""Ты — эксперт по профориентации. Проанализируй ответ ученика на вопрос квеста и определи, к какому типу профессии он склонен по методике Климова.

Ответ ученика: "{answer_text}"

Типы профессий:
- Ч-П (Человек-Природа): работа с растениями, животными, природой, экология
- Ч-Т (Человек-Техника): механизмы, инструменты, техника, инженерия, создание вещей
- Ч-Х (Человек-Художественный образ): творчество, искусство, музыка, литература, дизайн
- Ч-Ч (Человек-Человек): общение, помощь людям, обучение, медицина, управление
- Ч-З (Человек-Знаковая система): работа с информацией, числами, кодом, текстами, анализ

Оцени ответ по каждому типу от 0 до 3 баллов (где 3 — максимальное соответствие).

Верни ТОЛЬКО JSON в формате:
{{"Ч-П": число, "Ч-Т": число, "Ч-Х": число, "Ч-Ч": число, "Ч-З": число}}

Пример ответа: {{"Ч-П": 0, "Ч-Т": 3, "Ч-Х": 0, "Ч-Ч": 1, "Ч-З": 2}}"""

    # Пока используем заглушку - в реальной версии здесь будет вызов YandexGPT API
    # Для тестирования возвращаем примерные баллы на основе ключевых слов
    
    scores = {"Ч-П": 0, "Ч-Т": 0, "Ч-Х": 0, "Ч-Ч": 0, "Ч-З": 0}
    answer_lower = answer_text.lower()
    
    # Простой анализ по ключевым словам (временное решение)
    nature_words = ['природ', 'лес', 'растен', 'животн', 'эколог', 'дерев', 'земл', 'ферм', 'сад', 'огород']
    tech_words = ['механизм', 'техник', 'инженер', 'созда', 'постро', 'инструмент', 'устройств', 'компьютер', 'программ', 'код']
    art_words = ['творчеств', 'искусств', 'музык', 'литератур', 'дизайн', 'рисован', 'песн', 'стих', 'красот', 'вдохнов']
    people_words = ['люд', 'общен', 'помощ', 'обучен', 'медицин', 'учитель', 'врач', 'забот', 'поддерж', 'команд']
    info_words = ['информац', 'анализ', 'числ', 'данны', 'текст', 'код', 'математ', 'логик', 'систем', 'программ']
    
    for word in nature_words:
        if word in answer_lower:
            scores["Ч-П"] += 1
    for word in tech_words:
        if word in answer_lower:
            scores["Ч-Т"] += 1
    for word in art_words:
        if word in answer_lower:
            scores["Ч-Х"] += 1
    for word in people_words:
        if word in answer_lower:
            scores["Ч-Ч"] += 1
    for word in info_words:
        if word in answer_lower:
            scores["Ч-З"] += 1
    
    # Ограничиваем максимум 3 баллами
    for key in scores:
        scores[key] = min(scores[key], 3)
    
    # Если все нули - распределяем равномерно
    if sum(scores.values()) == 0:
        scores["Ч-Ч"] = 2  # По умолчанию - коммуникация
    
    return scores

