let activeQuestions = [];
let currentQuestion = 0;
let scores = { "Ч-П": 0, "Ч-Т": 0, "Ч-Х": 0, "Ч-Ч": 0, "Ч-З": 0 };
let isAnswering = false; // ЗАЩИТА ОТ ДВОЙНОГО КЛИКА

// === ОСНОВНАЯ ЛОГИКА ===

document.addEventListener('DOMContentLoaded', () => {
    const container = document.getElementById('questionsContainer');
    const progressFill = document.getElementById('progressFill');
    const questionCounter = document.getElementById('questionCounter');
    
    // 1. Перемешиваем все 20 вопросов и берём ровно 5
    activeQuestions = shuffleArray(allQuestions).slice(0, QUESTIONS_COUNT);
    
    // 2. Перемешиваем варианты ответов внутри выбранных вопросов
    activeQuestions = activeQuestions.map(q => ({
        ...q,
        options: shuffleArray(q.options)
    }));
    
    console.log(`✅ Загружено вопросов для этой сессии: ${activeQuestions.length}`);
    
    showQuestion(0);
    
    function showQuestion(index) {
        if (index >= activeQuestions.length) {
            finishOracle();
            return;
        }
        
        const q = activeQuestions[index];
        container.innerHTML = ''; // Очищаем предыдущий вопрос
        
        const questionBlock = document.createElement('div');
        questionBlock.className = 'question-block';
        questionBlock.style.opacity = '0';
        questionBlock.style.transform = 'scale(0.8)';
        
        const title = document.createElement('h3');
        title.textContent = q.text;
        questionBlock.appendChild(title);
        
        q.options.forEach((opt, optIndex) => {
            const label = document.createElement('label');
            label.className = 'option-label';
            label.style.opacity = '0';
            label.style.transform = 'translateX(-20px)';
            
            const input = document.createElement('input');
            input.type = 'radio';
            input.name = 'answer';
            input.value = opt.type;
            
            label.appendChild(input);
            label.appendChild(document.createTextNode(' ' + opt.text));
            
            // ИСПРАВЛЕНИЕ: добавляем e.preventDefault() и e.stopPropagation()
            label.addEventListener('click', (e) => {
                e.preventDefault();
                e.stopPropagation();
                handleAnswer(opt.type);
            });
            
            questionBlock.appendChild(label);
            
            setTimeout(() => {
                label.style.transition = 'all 0.4s ease';
                label.style.opacity = '1';
                label.style.transform = 'translateX(0)';
            }, 300 + (optIndex * 150));
        });
        
        container.appendChild(questionBlock);
        
        setTimeout(() => {
            questionBlock.style.transition = 'all 0.8s cubic-bezier(0.34, 1.56, 0.64, 1)';
            questionBlock.style.opacity = '1';
            questionBlock.style.transform = 'scale(1)';
        }, 100);
        
        const progress = ((index) / activeQuestions.length) * 100;
        progressFill.style.width = `${progress}%`;
        questionCounter.textContent = `Вопрос ${index + 1} из ${activeQuestions.length}`;
    }
    
    function handleAnswer(type) {
        // ЗАЩИТА: если уже идет обработка ответа, игнорируем повторный клик
        if (isAnswering) return;
        isAnswering = true;

        scores[type]++;
        
        const questionBlock = document.querySelector('.question-block');
        if (questionBlock) {
            questionBlock.style.transition = 'all 0.5s ease';
            questionBlock.style.opacity = '0';
            questionBlock.style.transform = 'scale(0.5) rotate(10deg)';
        }
        
        setTimeout(() => {
            currentQuestion++;
            isAnswering = false; // Снимаем блокировку для следующего вопроса
            showQuestion(currentQuestion);
        }, 600);
    }
    
    function finishOracle() {
        localStorage.setItem('oracleScores', JSON.stringify(scores));
        
        let maxScore = 0;
        let dominantType = "Ч-П";
        for (const [type, score] of Object.entries(scores)) {
            if (score > maxScore) {
                maxScore = score;
                dominantType = type;
            }
        }
        localStorage.setItem('dominantType', dominantType);
        
        container.innerHTML = `
            <div class="oracle-final" style="text-align: center; padding: 40px;">
                <div class="crystal-glow" style="font-size: 4em; margin-bottom: 20px;">🔮</div>
                <h3 style="color: #ffd700; font-size: 1.8em; margin-bottom: 20px;">Оракул увидел твой путь...</h3>
                <p style="color: #d4af37; font-size: 1.2em; margin-bottom: 30px;">
                    Кристалл хранит тайну. Она откроется после испытаний в Зале Совета.
                </p>
                <button class="btn-primary" onclick="window.location.href='quest.html'" style="max-width: 300px; margin: 0 auto;">
                    ⚔️ Перейти к испытаниям
                </button>
            </div>
        `;
        
        const finalBlock = container.querySelector('.oracle-final');
        if (finalBlock) {
            finalBlock.style.opacity = '0';
            finalBlock.style.transform = 'scale(0.8)';
            setTimeout(() => {
                finalBlock.style.transition = 'all 1s ease';
                finalBlock.style.opacity = '1';
                finalBlock.style.transform = 'scale(1)';
            }, 100);
        }
        
        progressFill.style.width = '100%';
        questionCounter.textContent = 'Пророчество получено';
    }
});